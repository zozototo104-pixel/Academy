import { describe, expect, test } from 'bun:test'
import { __testLimitProviderModelsForTests, __testProviderRateLimitCooldownForTests, __testQuestionVerifierCandidatePlan, modelFamily, parseProviderModelList } from '../../src/lib/text-ai'
import { __testVerifierExcludedProviders, __testVerifierFamilyAllowedForTests, __testVerifierPreferredProvidersForTests } from '../../src/lib/question-verifier'

describe('question verifier preferred routing', () => {
  test('preferred verifier is used first when available', () => {
    const preferred = parseProviderModelList('OPENAI:gpt-5.1')
    const fallback = parseProviderModelList('ANTHROPIC:claude-sonnet-4-5-20250929')
    const plan = __testQuestionVerifierCandidatePlan({ preferred, fallback, generatorProvider: 'TOPTOOLS', generatorModel: 'DeepSeek-V4-Pro' })

    expect(plan.ordered[0]).toEqual({ provider: 'OPENAI', model: 'gpt-5.1' })
  })

  test('preferred verifier from the same generator family is skipped', () => {
    const preferred = parseProviderModelList('OPENAI:deepseek-r1')
    const fallback = parseProviderModelList('ANTHROPIC:claude-sonnet-4-5-20250929')
    const plan = __testQuestionVerifierCandidatePlan({ preferred, fallback, generatorProvider: 'TOPTOOLS', generatorModel: 'DeepSeek-V4-Pro' })

    expect(plan.ordered[0]).toEqual({ provider: 'ANTHROPIC', model: 'claude-sonnet-4-5-20250929' })
    expect(plan.diagnostics.some((line) => line.includes('SAME_FAMILY_AS_GENERATOR'))).toBe(true)
  })

  test('all preferred verifiers on cooldown fall back to normal candidates', () => {
    const preferred = parseProviderModelList('OPENAI:gpt-5.1,ANTHROPIC:claude-sonnet-4-5-20250929')
    const fallback = parseProviderModelList('GEMINI:gemini-2.5-pro')
    const plan = __testQuestionVerifierCandidatePlan({ preferred, fallback, cooldown: ['OPENAI:gpt-5.1', 'ANTHROPIC:claude-sonnet-4-5-20250929'] })

    expect(plan.ordered[0]).toEqual({ provider: 'GEMINI', model: 'gemini-2.5-pro' })
    expect(plan.diagnostics.filter((line) => line.includes('COOLDOWN')).length).toBe(2)
  })

  test('empty preferred verifier setting does not change fallback behavior', () => {
    const preferred = parseProviderModelList('')
    const fallback = parseProviderModelList('GEMINI:gemini-2.5-pro,OPENAI:gpt-5.1')
    const plan = __testQuestionVerifierCandidatePlan({ preferred, fallback })

    expect(plan.ordered).toEqual(fallback)
  })

  test('diagnostics include cooldown and no-balance reasons', () => {
    const preferred = parseProviderModelList('OPENAI:gpt-5.1,ANTHROPIC:claude-sonnet-4-5-20250929')
    const plan = __testQuestionVerifierCandidatePlan({ preferred, cooldown: ['OPENAI:gpt-5.1'], noBalance: ['ANTHROPIC'] })

    expect(plan.diagnostics.some((line) => line.includes('OPENAI:gpt-5.1 COOLDOWN'))).toBe(true)
    expect(plan.diagnostics.some((line) => line.includes('ANTHROPIC:claude-sonnet-4-5-20250929 NO_BALANCE'))).toBe(true)
  })

  test('verifier limits UnoRouter candidates to three models', () => {
    const models = ['u1', 'u2', 'u3', 'u4', 'u5']
    expect(__testLimitProviderModelsForTests('UNOROUTER', models, { UNOROUTER: 3 })).toEqual(['u1', 'u2', 'u3'])
  })

  test('verifier UnoRouter provider cooldown trips after three 429s in one minute', () => {
    const now = Date.now()
    expect(__testProviderRateLimitCooldownForTests([now - 50_000, now - 25_000], now, 3, 60_000)).toBe(false)
    expect(__testProviderRateLimitCooldownForTests([now - 50_000, now - 25_000, now], now, 3, 60_000)).toBe(true)
  })

  test('verifier prefers Groq or Gemini before UnoRouter when not generated by the same provider', () => {
    expect(__testVerifierPreferredProvidersForTests('GEMINI')).toEqual(['GROQ', 'UNOROUTER'])
    expect(__testVerifierPreferredProvidersForTests('GROQ')).toEqual(['GEMINI', 'UNOROUTER'])
  })

  test('Alborihi self-review requires the explicit router exception and is preferred before fallbacks', () => {
    expect(__testVerifierExcludedProviders('ALBORIHI')).toEqual(['ALBORIHI'])
    expect(__testVerifierPreferredProvidersForTests('ALBORIHI')).toEqual(['ALBORIHI', 'GROQ', 'GEMINI', 'UNOROUTER'])
    expect(__testVerifierExcludedProviders('GEMINI')).toEqual(['GEMINI'])
    expect(__testVerifierExcludedProviders('GROQ')).toEqual(['GROQ'])
  })

  test('Alborihi cross-family self-review accepts GPT after Claude but never Claude after Claude', () => {
    const generatorFamily = modelFamily('claude-sonnet-5')
    expect(__testVerifierFamilyAllowedForTests({ provider: 'ALBORIHI', model: 'gpt-5.6-luna' }, 'ALBORIHI', generatorFamily)).toEqual({ ok: true })
    expect(__testVerifierFamilyAllowedForTests({ provider: 'ALBORIHI', model: 'claude-opus-4-6' }, 'ALBORIHI', generatorFamily)).toEqual({ ok: false, reason: 'VERIFIER_SAME_FAMILY' })
    expect(__testVerifierFamilyAllowedForTests({ provider: 'ALBORIHI', model: 'unknown-experimental-model' }, 'ALBORIHI', generatorFamily)).toEqual({ ok: false, reason: 'VERIFIER_SAME_FAMILY_OR_UNKNOWN' })
  })

  test('Alborihi can fall back to a different provider with a different known model family', () => {
    expect(__testVerifierFamilyAllowedForTests({ provider: 'GROQ', model: 'llama-3.3-70b-versatile' }, 'ALBORIHI', modelFamily('claude-sonnet-5'))).toEqual({ ok: true })
  })
})
